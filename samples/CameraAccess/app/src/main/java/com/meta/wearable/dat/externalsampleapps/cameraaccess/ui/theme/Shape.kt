/**
 * Corner radii. Softer than the Material 3 defaults, echoing the rounded terminals of the "U" in the
 * logo. `medium` is the workhorse — every occurrence card uses it; `large` is reserved for surfaces
 * that slide in over content (the map's bottom sheet, modal sheets).
 */
val UrbanSenseShapes =
    Shapes(
        extraSmall = RoundedCornerShape(6.dp),
        small = RoundedCornerShape(8.dp),
        medium = RoundedCornerShape(16.dp),
        large = RoundedCornerShape(24.dp),
        extraLarge = RoundedCornerShape(32.dp),
    )
